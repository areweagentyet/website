// Run through playwright-cli run-code. No @playwright/test dependency is required.
async (page) => {
  const passed = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (condition, label) => { if (!condition) throw new Error(label); passed.push(label); };
  const count = async () => await page.locator('#result-count').textContent();
  await page.goto('http://127.0.0.1:4321/');
  await page.getByRole('searchbox', { name: 'Search solutions' }).waitFor();
  check((await count()).includes('239'), 'All 239 entries load');
  check(await page.locator('#catalog-rows tr:visible').count() === 18, 'Progressive list initially shows 18');
  await page.getByRole('button', { name: 'Show more solutions' }).click();
  check(await page.locator('#catalog-rows tr:visible').count() === 48, 'Load more reveals 30 additional entries');
  await page.getByRole('combobox', { name: 'Sort solutions' }).selectOption('name');
  check((await page.locator('#catalog-rows tr:visible .solution-name').first().textContent()).trim() === '802.1Qaz ETS', 'Name sort changes visible result order');
  check(page.url().includes('sort=name'), 'Sort selection is shareable in URL');
  await page.getByRole('link', { name: 'Give it memory 8' }).click();
  check((await count()).includes('8 building blocks'), 'Task filter narrows to memory');
  check(page.url().includes('task=memory'), 'Task state appears in URL');
  check(await page.locator('#task-context').isVisible(), 'Task guide is visible');
  await page.getByRole('combobox', { name: 'Entry type', exact: true }).selectOption('model');
  check(await page.locator('#empty-results').isVisible(), 'Incompatible combined filters have useful empty state');
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.getByRole('searchbox').fill('huggingface_hub');
  check(await page.locator('#catalog-rows tr:visible').count() === 1, 'Alias search finds one record');
  check(await page.getByRole('link', { name: 'Hugging Face Hub', exact: true }).isVisible(), 'Alias finds Hugging Face Hub');
  await page.getByRole('searchbox').fill('智能体运行框架');
  check((await count()).includes('47 building blocks'), 'Chinese category labels are searchable');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByRole('combobox', { name: 'Readiness', exact: true }).selectOption('assessed');
  check((await count()).includes('13 building blocks'), 'Assessed-only filter returns 13');
  await page.reload();
  check(await page.getByRole('combobox', { name: 'Readiness', exact: true }).inputValue() === 'assessed', 'Filters survive reload');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByRole('link', { name: 'Give it memory 8' }).click();
  await page.goBack();
  check(await page.locator('[data-task=""]').getAttribute('aria-current') === 'true', 'Browser back restores previous task');
  await page.goto('http://127.0.0.1:4321/compare/?with=mem0,graphiti');
  await page.getByRole('table', { name: 'Solution evidence comparison' }).waitFor();
  check(await page.locator('#comparison-table thead th').count() === 3, 'Shared comparison renders two solutions');
  await page.getByRole('link', { name: 'Explore', exact: true }).click();
  await page.waitForLoadState('load');
  check((await page.locator('.nav-compare').textContent()).includes('2'), 'Shared selection survives navigation before edits');
  await page.locator('.nav-compare').click();
  await page.waitForLoadState('load');
  await page.getByRole('combobox', { name: 'Add a building block' }).selectOption('langgraph');
  check(await page.locator('#comparison-table thead th').count() === 4, 'Third solution is added');
  check(await page.getByRole('combobox', { name: 'Add a building block' }).isDisabled(), 'Picker enforces three-item limit');
  await page.getByRole('button', { name: 'Remove LangGraph from comparison' }).focus();
  await page.keyboard.press('Enter');
  check(await page.locator('#comparison-table thead th').count() === 3, 'Comparison removal works');
  check(await page.evaluate(() => document.activeElement?.getAttribute('aria-label') === 'Remove Mem0 from comparison'), 'Comparison removal preserves keyboard focus');
  await page.getByRole('link', { name: 'Explore', exact: true }).click();
  await page.waitForLoadState('load');
  check((await page.locator('.nav-compare').textContent()).includes('2'), 'Comparison survives navigation');
  await page.getByRole('button', { name: 'Add Firecracker to comparison' }).click();
  await page.getByRole('button', { name: 'Add LangGraph to comparison' }).click();
  check((await page.locator('#announcement').textContent()).includes('three solutions'), 'Fourth comparison selection is rejected with feedback');
  await page.locator('#compare-selection').getByRole('button', { name: 'Remove Mem0 from comparison' }).focus();
  await page.keyboard.press('Enter');
  check(await page.evaluate(() => document.querySelector('#compare-selection').contains(document.activeElement)), 'Shortlist removal preserves keyboard focus');
  await page.getByRole('button', { name: 'Clear comparison', exact: true }).click();
  check(await page.locator('#compare-tray').isHidden(), 'Clear shortlist hides tray');
  await page.goto('http://127.0.0.1:4321/stack/?domain=trace-evidence#catalog');
  check((await count()).includes('17 building blocks'), 'Stack links apply category filters');
  await page.goto('http://127.0.0.1:4321/solutions/langgraph/');
  check(await page.getByRole('heading', { name: 'Follow the evidence.' }).isVisible(), 'Assessed profile contains linked evidence');
  check(await page.locator('.evidence-link').count() === 3, 'LangGraph profile has three primary sources');
  await page.goto('http://127.0.0.1:4321/solutions/openfab/');
  check(await page.getByRole('heading', { name: 'Not yet reviewed.', exact: false }).count() === 1, 'Unassessed profile says review pending');
  await page.goto('http://127.0.0.1:4321/compare/?with=missing,mem0,mem0,graphiti,e2b,langgraph');
  check(await page.locator('#comparison-table thead th').count() === 4, 'Malformed shared selection is normalized to three valid entries');
  check(await page.locator('#comparison-notice').isVisible(), 'Malformed comparison shows explanation');
  await page.setViewportSize({ width: 390, height: 844 });
  for (const path of ['/', '/stack/', '/solutions/langgraph/', '/solutions/openfab/', '/methodology/', '/compare/?with=mem0,graphiti']) {
    await page.goto('http://127.0.0.1:4321' + path);
    const fits = await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth);
    check(fits, 'Mobile layout fits viewport: ' + path);
  }
  await page.goto('http://127.0.0.1:4321/?task=memory#catalog');
  check(await page.evaluate(() => {
    const active = document.querySelector('.task-link.active').getBoundingClientRect();
    const list = document.querySelector('.task-links').getBoundingClientRect();
    return active.left >= list.left - 1 && active.right <= list.right + 1;
  }), 'Selected task is visible in the horizontal mobile task rail');
  check(errors.length === 0, 'No browser runtime errors: ' + errors.join('; '));
  return { passed: passed.length, checks: passed };
}
